/**
 * apps/web/src/app/api/auth/oauth/route.ts
 * Uses @supabase/ssr createServerClient so PKCE code_verifier cookies are persisted
 * directly onto the NextResponse redirect for /api/auth/callback.
 * Supports ?next=/path (open-redirect guarded) and redirects errors to /login?error=...
 */
import { cookies } from 'next/headers';
import { NextResponse } from 'next/server';
import { createServerClient, type CookieOptions } from '@supabase/ssr';

const ALLOWED_PROVIDERS = new Set(['google', 'kakao']);
const PENDING_SHARE_COOKIE = 'ws_pending_share_token';
const OAUTH_NEXT_COOKIE = 'ws_oauth_next';

function sanitizeNextPath(raw: string | null): string {
  if (!raw || !raw.startsWith('/') || raw.startsWith('//')) {
    return '/today';
  }
  return raw;
}

export async function GET(req: Request) {
  const reqUrl = new URL(req.url);
  const { searchParams } = reqUrl;
  const appOrigin = process.env.NEXT_PUBLIC_APP_ORIGIN ?? reqUrl.origin;

  const provider = searchParams.get('provider') ?? '';
  const shareToken = searchParams.get('shareToken')?.trim() ?? '';
  const safeNext = sanitizeNextPath(searchParams.get('next'));

  if (!ALLOWED_PROVIDERS.has(provider)) {
    return NextResponse.redirect(`${appOrigin}/login?error=invalid_provider`, { status: 302 });
  }

  const supabaseUrl = process.env.NEXT_PUBLIC_SUPABASE_URL;
  const supabaseAnonKey = process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY;
  if (!supabaseUrl || !supabaseAnonKey) {
    return NextResponse.redirect(`${appOrigin}/login?error=oauth_init_failed`, { status: 302 });
  }

  const cookieStore = await cookies();
  const cookiesToSet: Array<{ name: string; value: string; options: CookieOptions }> = [];

  const supabase = createServerClient(supabaseUrl, supabaseAnonKey, {
    cookies: {
      getAll() {
        return cookieStore.getAll();
      },
      setAll(list) {
        cookiesToSet.push(...list);
      },
    },
  });

  const redirectTo = `${appOrigin}/api/auth/callback`;
  const { data, error } = await supabase.auth.signInWithOAuth({
    provider: provider as 'google' | 'kakao',
    options: { redirectTo },
  });

  if (error || !data?.url) {
    return NextResponse.redirect(`${appOrigin}/login?error=oauth_init_failed`, { status: 302 });
  }

  const res = NextResponse.redirect(data.url, { status: 302 });
  res.headers.set('Cache-Control', 'no-store');

  // Attach PKCE code_verifier cookies generated by @supabase/ssr onto the redirect response
  for (const { name, value, options } of cookiesToSet) {
    res.cookies.set(name, value, options);
  }

  const cookieBase = {
    httpOnly: true,
    sameSite: 'lax' as const,
    secure: process.env.NODE_ENV === 'production',
    path: '/',
    maxAge: 600,
  };

  res.cookies.set(OAUTH_NEXT_COOKIE, safeNext, cookieBase);

  if (shareToken && shareToken.length >= 16 && shareToken.length <= 256) {
    res.cookies.set(PENDING_SHARE_COOKIE, shareToken, cookieBase);
  }

  return res;
}
